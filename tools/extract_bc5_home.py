"""Extract only the authenticated BC5 Home image lists; preserve BC4 assets."""
import hashlib
import json
import struct
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def main():
    evidence = json.loads((ROOT / 'docs/reference/bc5/runtime-rea.json').read_text(encoding='utf-8-sig'))['normalized_result']
    binary = Path(evidence['artifact']['path']).read_bytes()
    assert hashlib.sha256(binary).hexdigest() == evidence['artifact']['sha256']
    sources = []
    manifest = []
    for scale in [100, 125, 150, 200]:
        form = 'TBCIMAGES' + ('' if scale == 100 else f'_{scale}')
        resource = next(r for r in evidence['resources'] if r['name'].get('name') == form)
        location = resource['payload']['location']
        data = binary[location['offset']:location['offset'] + location['bytes']]
        assert hashlib.sha256(data).hexdigest() == resource['payload']['sha256']
        tree = json.loads((ROOT / f'docs/reference/bc5/forms/{form}.json').read_text(encoding='utf-8'))
        for node in tree['children']:
            if node['name'] not in ['HomeImages', 'HomeMediumImages']:
                continue
            props = node['props']
            blob = props['ImagesBitmap.Data']['binary']
            raw = data[blob['offset']:blob['offset'] + blob['bytes']]
            assert hashlib.sha256(raw).hexdigest() == blob['sha256']
            bmp = raw[raw.index(b'BM'):]
            offset = struct.unpack_from('<I', bmp, 10)[0]
            width, height = struct.unpack_from('<ii', bmp, 18)
            assert struct.unpack_from('<H', bmp, 28)[0] == 32
            sheet = Image.frombytes('RGBA', (width, abs(height)), bmp[offset:], 'raw', 'BGRA', width * 4, -1 if height > 0 else 1)
            w, h = props['Width'], props['Height']
            for index, name in enumerate(props['ImageNames.Strings']):
                x, y = index % (width // w) * w, index // (width // w) * h
                path = Path(f'assets/bc5/home/{scale}/{node["name"]}/{name}.png')
                (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
                sheet.crop((x, y, x + w, y + h)).save(ROOT / path)
                sources.append(f'    ("{name}", "{node["name"]}", {scale}, include_bytes!("../../{path.as_posix()}")),')
                manifest.append(dict(path=path.as_posix(), size=[w, h], sha256=hashlib.sha256((ROOT / path).read_bytes()).hexdigest()))
    (ROOT / 'src/ui/bc5_home_icons.rs').write_text('// Generated by tools/extract_bc5_home.py; isolated BC5 resource evidence.\nconst BC5_HOME_ICONS: &[crate::resources::IconSource] = &[\n' + '\n'.join(sources) + '\n];\n', encoding='utf-8')
    (ROOT / 'docs/reference/bc5/home-icons.json').write_text(json.dumps(dict(reference_sha256=evidence['artifact']['sha256'], icons=manifest), indent=2) + '\n', encoding='utf-8')
    print(f'Extracted {len(manifest)} authenticated Home icon variants.')


if __name__ == '__main__':
    main()
